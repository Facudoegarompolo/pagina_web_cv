import { DatabaseSync } from 'node:sqlite';
import { copyFileSync, existsSync, mkdirSync, mkdtempSync, readFileSync, realpathSync, renameSync, rmSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve, sep } from 'node:path';
import { fileURLToPath } from 'node:url';
import { fileReferences, publicContent, validatePublication } from '../lib/content.mjs';

const root = fileURLToPath(new URL('..', import.meta.url));
const marker = '.portfolio-export';
function relativeMedia(value) {
  if (typeof value === 'string') return /^\/media\/[a-zA-Z0-9.-]+$/.test(value) ? `.${value}` : value;
  if (Array.isArray(value)) return value.map(relativeMedia);
  if (value && typeof value === 'object') return Object.fromEntries(Object.entries(value).map(([key, item]) => [key, relativeMedia(item)]));
  return value;
}

export function exportPages({ dataDir = resolve(process.env.DATA_DIR || join(root, 'data')), outputDir = join(root, 'docs') } = {}) {
  const database = join(dataDir, 'portfolio.sqlite');
  if (!existsSync(database)) throw new Error('Falta la base local. Iniciá la web, cargá el contenido y publicalo en el panel antes de exportar.');
  if (existsSync(outputDir) && !existsSync(join(outputDir, marker))) throw new Error('La carpeta de salida ya existe y no es una exportación del portfolio. No se modificó.');
  const db = new DatabaseSync(database, { readOnly: true });
  let payload;
  try {
    const row = db.prepare("SELECT json, updated FROM content WHERE kind='published'").get();
    if (!row) throw new Error('No hay contenido publicado para exportar.');
    payload = { content: publicContent(JSON.parse(row.json)), updated: row.updated };
    validatePublication(payload.content);
  } finally { db.close(); }
  const refs = fileReferences(payload.content);
  const uploads = realpathSync(join(dataDir, 'uploads'));
  const sources = [...refs].map(id => {
    if (!/\.(pdf|png|jpe?g|webp)$/i.test(id)) throw new Error(`Formato de archivo no permitido: ${id}`);
    const path = realpathSync(join(uploads, id));
    if (!path.startsWith(uploads + sep)) throw new Error('Un archivo publicado apunta fuera de uploads.');
    return { id, path };
  });
  mkdirSync(dirname(outputDir), { recursive: true });
  const staging = mkdtempSync(join(dirname(outputDir), '.pages-export-'));
  try {
    mkdirSync(join(staging, 'assets'));
    mkdirSync(join(staging, 'media'));
    let html = readFileSync(join(root, 'public/index.html'), 'utf8');
    html = html.replace('<html lang="es">', '<html lang="es" data-content-url="./content.json">');
    html = html.replace(/(href|src)="\/(?!\/)/g, '$1="./');
    writeFileSync(join(staging, 'index.html'), html);
    const css = readFileSync(join(root, 'public/style.css'), 'utf8').replaceAll("url('/assets/", "url('./assets/");
    writeFileSync(join(staging, 'style.css'), css);
    for (const file of ['app.js', 'desktop.js', 'artwork.js', 'favicon.svg']) copyFileSync(join(root, 'public', file), join(staging, file));
    for (const file of ['desktop.jpg', 'mobile.jpg']) copyFileSync(join(root, 'public/assets', file), join(staging, 'assets', file));
    for (const { id, path } of sources) copyFileSync(path, join(staging, 'media', id));
    writeFileSync(join(staging, 'content.json'), JSON.stringify({ ...payload, content: relativeMedia(payload.content) }, null, 2) + '\n');
    writeFileSync(join(staging, '.nojekyll'), '');
    writeFileSync(join(staging, marker), 'Generated by npm run export:pages. Do not edit this directory directly.\n');
    if (existsSync(join(outputDir, 'CNAME'))) copyFileSync(join(outputDir, 'CNAME'), join(staging, 'CNAME'));
    if (existsSync(outputDir)) rmSync(outputDir, { recursive: true });
    renameSync(staging, outputDir);
  } catch (e) { rmSync(staging, { recursive: true, force: true }); throw e; }
  return { outputDir, files: sources.length, updated: payload.updated };
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const result = exportPages();
  console.log(`Exportado a ${result.outputDir}\nContenido publicado: ${result.updated}\nArchivos públicos: ${result.files}\nPanel, borradores, sesiones y contraseñas excluidos.`);
}
